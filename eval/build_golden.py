def main() -> None:
    rows = []
    for (qid, tier), answer in ANSWERS.items():
        q = Q[qid]
        rows.append({
            "id": f"{qid}-{tier}",
            "qid": qid,
            "tier": tier,
            "topic": q["topic"],
            "question": q["question"],
            "answer": answer,
            "expected_rank": {"bad": 1, "mid": 2, "good": 3}[tier],
        })
    out = ROOT / "eval" / "golden.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
